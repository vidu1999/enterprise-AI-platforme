import { BadRequestException, Injectable, NotFoundException } from '@nestjs/common';
import { DatabaseService } from '../database/database.service';
import { NotificationsService } from '../notifications/notifications.service';
import { NotificationType } from '../common/enums';

@Injectable()
export class WorkflowService {
  constructor(
    private readonly db: DatabaseService,
    private readonly notifications: NotificationsService,
  ) {}

  async listPos(companyId: string) {
    const pos = await this.db.many(
      `SELECT po.id, po.company_id AS "companyId", po.number, po.supplier_id AS "supplierId",
              s.name AS "supplierName", po.status, po.auto_generated AS "autoGenerated",
              po.notes, po.total, po.created_at AS "createdAt", po.updated_at AS "updatedAt"
       FROM "purchase_orders" po
       JOIN "suppliers" s ON s.id = po.supplier_id
       WHERE po.company_id = $1
       ORDER BY po.created_at DESC`,
      [companyId],
    );
    if (!pos.length) return [];

    const orderIds = pos.map((p) => p.id);
    const lines = await this.db.many(
      `SELECT l.id, l.order_id AS "orderId", l.item_id AS "itemId",
              l.quantity, l.unit_cost AS "unitCost",
              i.sku, i.name AS "itemName", i.unit
       FROM "purchase_order_lines" l
       JOIN "inventory_items" i ON i.id = l.item_id
       WHERE l.order_id = ANY($1::uuid[])`,
      [orderIds],
    );

    const linesByOrder = new Map<string, any[]>();
    for (const l of lines) {
      const list = linesByOrder.get(l.orderId) ?? [];
      list.push({
        id: l.id,
        itemId: l.itemId,
        quantity: Number(l.quantity),
        unitCost: Number(l.unitCost),
        item: { id: l.itemId, sku: l.sku, name: l.itemName, unit: l.unit },
      });
      linesByOrder.set(l.orderId, list);
    }

    return pos.map((p) => ({
      id: p.id,
      companyId: p.companyId,
      number: p.number,
      supplierId: p.supplierId,
      supplier: { id: p.supplierId, name: p.supplierName },
      status: p.status,
      autoGenerated: p.autoGenerated,
      notes: p.notes,
      total: Number(p.total ?? 0),
      lines: linesByOrder.get(p.id) ?? [],
      createdAt: p.createdAt,
      updatedAt: p.updatedAt,
    }));
  }

  async createPo(companyId: string, requesterId: string, dto: { supplierId: string; notes?: string; lines: Array<{ itemId: string; quantity: number; unitCost: number }> }) {
    if (!dto.lines?.length) throw new BadRequestException('Purchase order requires at least one line item');

    const supplier = await this.db.one<{ id: string; name: string }>(
      `SELECT id, name FROM "suppliers" WHERE id = $1 AND company_id = $2`,
      [dto.supplierId, companyId],
    );
    if (!supplier) throw new NotFoundException('Supplier not found');

    const total = dto.lines.reduce((sum, l) => sum + Number(l.quantity) * Number(l.unitCost), 0);
    const number = `PO-${Date.now().toString(36).toUpperCase()}`;

    const created = await this.db.withTransaction(async (tx) => {
      const po = (await tx.one<{ id: string }>(
        `INSERT INTO "purchase_orders" (company_id, number, supplier_id, status, auto_generated, notes, total)
         VALUES ($1, $2, $3, 'PENDING', FALSE, $4, $5)
         RETURNING id`,
        [companyId, number, dto.supplierId, dto.notes ?? null, total],
      ))!;

      for (const line of dto.lines) {
        const item = await tx.one(
          `SELECT id FROM "inventory_items" WHERE id = $1 AND company_id = $2`,
          [line.itemId, companyId],
        );
        if (!item) throw new NotFoundException(`Inventory item ${line.itemId} not found`);
        await tx.query(
          `INSERT INTO "purchase_order_lines" (order_id, item_id, quantity, unit_cost)
           VALUES ($1, $2, $3, $4)`,
          [po.id, line.itemId, line.quantity, line.unitCost],
        );
      }

      const approvalTitle = `Purchase Order ${number} — ${supplier.name} (total ${total.toLocaleString()})`;
      const approval = await tx.one<{ id: string }>(
        `INSERT INTO "approvals" (company_id, type, ref_id, title, requested_by_id, amount, status)
         VALUES ($1, 'PURCHASE_ORDER', $2, $3, $4, $5, 'PENDING')
         RETURNING id`,
        [companyId, po.id, approvalTitle, requesterId, total],
      );

      return { poId: po.id, approvalTitle, approvalId: approval?.id };
    });

    await this.notifications.notifyRoles(
      companyId,
      ['COMPANY_ADMIN', 'MANAGER'],
      NotificationType.APPROVAL_REQUESTED,
      'Purchase order approval requested',
      created.approvalTitle,
    );

    const all = await this.listPos(companyId);
    return all.find((p) => p.id === created.poId);
  }

  async receivePo(companyId: string, actorId: string, id: string) {
    const po = await this.db.one<any>(
      `SELECT id, number, status FROM "purchase_orders" WHERE id = $1 AND company_id = $2`,
      [id, companyId],
    );
    if (!po) throw new NotFoundException('Purchase order not found');
    if (po.status !== 'APPROVED') {
      throw new BadRequestException(`Only APPROVED purchase orders can be received (current: ${po.status})`);
    }

    await this.db.withTransaction(async (tx) => {
      const lines = await tx.many<{ itemId: string; quantity: number }>(
        `SELECT item_id AS "itemId", quantity FROM "purchase_order_lines" WHERE order_id = $1`,
        [id],
      );
      for (const l of lines) {
        await tx.query(
          `UPDATE "inventory_items" SET quantity = quantity + $3, updated_at = NOW()
           WHERE id = $1 AND company_id = $2`,
          [l.itemId, companyId, Number(l.quantity)],
        );
        await tx.query(
          `INSERT INTO "inventory_transactions" (company_id, item_id, actor_id, type, quantity, note)
           VALUES ($1, $2, $3, 'IN', $4, $5)`,
          [companyId, l.itemId, actorId, Number(l.quantity), `Received via ${po.number}`],
        );
      }
      await tx.query(
        `UPDATE "purchase_orders" SET status = 'RECEIVED', updated_at = NOW()
         WHERE id = $1 AND company_id = $2`,
        [id, companyId],
      );
    });

    return { ok: true, number: po.number, status: 'RECEIVED' };
  }

  async listApprovals(companyId: string, status?: string) {
    const rows = await this.db.many(
      `SELECT a.id, a.company_id AS "companyId", a.type, a.ref_id AS "refId",
              a.title, a.amount, a.status, a.comment,
              a.decided_at AS "decidedAt", a.created_at AS "createdAt",
              req.first_name AS "reqFirstName", req.last_name AS "reqLastName",
              app.first_name AS "appFirstName", app.last_name AS "appLastName"
       FROM "approvals" a
       LEFT JOIN "users" req ON req.id = a.requested_by_id
       LEFT JOIN "users" app ON app.id = a.approver_id
       WHERE a.company_id = $1
         AND ($2::text IS NULL OR a.status::text = $2)
       ORDER BY (a.status = 'PENDING') DESC, a.created_at DESC`,
      [companyId, status || null],
    );
    return rows.map((r) => ({
      id: r.id,
      companyId: r.companyId,
      type: r.type,
      refId: r.refId,
      title: r.title,
      amount: Number(r.amount ?? 0),
      status: r.status,
      comment: r.comment,
      decidedAt: r.decidedAt,
      createdAt: r.createdAt,
      requestedBy: r.reqFirstName ? `${r.reqFirstName} ${r.reqLastName}` : 'System Automation',
      approvedBy: r.appFirstName ? `${r.appFirstName} ${r.appLastName}` : null,
    }));
  }

  async decide(companyId: string, approverId: string, id: string, dto: { decision: string; comment?: string }) {
    if (!['APPROVED', 'REJECTED'].includes(dto.decision)) {
      throw new BadRequestException('Decision must be APPROVED or REJECTED');
    }

    const approval = await this.db.one<any>(
      `SELECT id, type, ref_id AS "refId", title, status, requested_by_id AS "requestedById"
       FROM "approvals" WHERE id = $1 AND company_id = $2`,
      [id, companyId],
    );
    if (!approval) throw new NotFoundException('Approval request not found');
    if (approval.status !== 'PENDING') throw new BadRequestException('Approval has already been decided');

    const updated = await this.db.withTransaction(async (tx) => {
      const row = await tx.one(
        `UPDATE "approvals"
         SET status = $3::"ApprovalStatus",
             approver_id = $4,
             decided_at = NOW(),
             comment = $5
         WHERE id = $1 AND company_id = $2
         RETURNING id, company_id AS "companyId", type, ref_id AS "refId",
                   title, status, comment, decided_at AS "decidedAt"`,
        [id, companyId, dto.decision, approverId, dto.comment ?? null],
      );

      if (approval.type === 'PURCHASE_ORDER') {
        await tx.query(
          `UPDATE "purchase_orders" SET status = $3::"ApprovalStatus", updated_at = NOW()
           WHERE id = $1 AND company_id = $2`,
          [approval.refId, companyId, dto.decision],
        );
      }
      return row;
    });

    if (approval.requestedById) {
      await this.notifications.push(
        companyId,
        approval.requestedById,
        dto.decision === 'APPROVED' ? NotificationType.APPROVED : NotificationType.REJECTED,
        `Request ${dto.decision.toLowerCase()}`,
        `${approval.title} was ${dto.decision.toLowerCase()}${dto.comment ? ` — "${dto.comment}"` : ''}.`,
      );
    }

    return updated;
  }
}
